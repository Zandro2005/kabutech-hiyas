#!/usr/bin/env python3
"""
KabuTech Hiyas — Edge AI Forecaster Trainer (for Edge Impulse BYOM)

Trains a tiny multi-output regression model that predicts how temperature,
humidity, CO2 and light will CHANGE over the next 10 minutes, from the last
10 minutes of readings (20 samples @ 30 s, 4 sensors = 80 inputs).

Outputs (all written to tinyml/model/):
  forecaster.keras            Keras model (for reference / re-training)
  forecaster_float32.tflite   Float model
  forecaster_int8.tflite      Fully int8-quantized model  -> upload to Edge Impulse (BYOM)
  representative.npy          Calibration data            -> upload to Edge Impulse (BYOM)
  test_x.npy / test_y.npy     Held-out data for checking
  normalization.json          Means / std-devs used for scaling
  ../../firmware/kabutech_prototype/edge_forecast_norm.h   Same constants as a C header

Usage (from the repository root):
  tinyml\\.venv\\Scripts\\python.exe tinyml\\train_forecaster.py
  tinyml\\.venv\\Scripts\\python.exe tinyml\\train_forecaster.py --real tinyml\\real_sequences.csv --epochs 80

Feature layout (IMPORTANT — the firmware builds its input in exactly this order):
  interleaved per time step, oldest first: [T, H, CO2, L] x 20  (80 values)
  steps 0..18 : (x[i] - x[latest]) / rel_std[s]      <- trend relative to now
  step  19    : (x[latest] - mean[s]) / std[s]        <- current absolute level
Targets: normalized deltas  (x(t+20) - x(t0)) / delta_std[i]
"""

import argparse
import csv
import json
import os
import random
from collections import defaultdict

import numpy as np

HERE = os.path.dirname(os.path.abspath(__file__))
REPO = os.path.dirname(HERE)
MODEL_DIR = os.path.join(HERE, "model")
FW_HEADER = os.path.join(REPO, "firmware", "kabutech_prototype", "edge_forecast_norm.h")

SENSORS = ["temperature", "humidity", "co2", "light"]
UNITS = ["°C", "%RH", "ppm", "lux"]
STEP_MS = 30_000
WINDOW = 20      # 20 x 30 s = 10 min history
HORIZON = 20     # 20 x 30 s = 10 min ahead
GAP_MS = 90_000  # a gap larger than this starts a new sequence (real recordings)


# ─────────────────────────────── Data loading ───────────────────────────────

def load_sequences(path, id_prefix):
    """Return list of np.ndarray [n_steps, 4]. Splits on timestamp gaps."""
    by_id = defaultdict(list)
    with open(path, newline="", encoding="utf-8") as f:
        for row in csv.DictReader(f):
            try:
                vals = [float(row[s]) for s in SENSORS]
            except (KeyError, ValueError):
                continue
            if any(v <= -999 for v in vals):       # skip faulted readings
                continue
            sid = f"{id_prefix}{row.get('sequence_id', '0')}"
            by_id[sid].append((float(row["timestamp"]), vals))

    sequences = []
    for sid, rows in by_id.items():
        rows.sort(key=lambda r: r[0])
        current = [rows[0][1]]
        for (t_prev, _), (t, v) in zip(rows, rows[1:]):
            if t - t_prev > GAP_MS:
                sequences.append(np.array(current, dtype=np.float32))
                current = []
            current.append(v)
        sequences.append(np.array(current, dtype=np.float32))
    return [s for s in sequences if len(s) >= WINDOW + HORIZON]


def make_windows(seq):
    n = len(seq) - WINDOW - HORIZON + 1
    xs = np.stack([seq[i:i + WINDOW] for i in range(n)])               # [n, W, 4]
    ys = seq[WINDOW - 1 + HORIZON: WINDOW - 1 + HORIZON + n] - seq[WINDOW - 1: WINDOW - 1 + n]
    return xs, ys


def build_split(sequences, test_frac, rng):
    idx = list(range(len(sequences)))
    rng.shuffle(idx)
    n_test = max(1, int(len(idx) * test_frac))
    test_ids, train_ids = set(idx[:n_test]), idx[n_test:]

    def collect(ids):
        X, Y = [], []
        for i in ids:
            x, y = make_windows(sequences[i])
            X.append(x)
            Y.append(y)
        return np.concatenate(X), np.concatenate(Y)

    return collect(train_ids), collect(sorted(test_ids))


# ─────────────────────────────── Export helpers ─────────────────────────────

def write_c_header(norm):
    def arr(name, vals):
        return f"static const float {name}[4] = {{ " + ", ".join(f"{v:.6f}f" for v in vals) + " };"

    text = f"""// AUTO-GENERATED by tinyml/train_forecaster.py — do not edit by hand.
// Re-run the trainer after retraining so the firmware scaling matches the model.
#pragma once

#define EF_WINDOW        {WINDOW}     // history steps
#define EF_HORIZON       {HORIZON}     // steps ahead
#define EF_STEP_MS       {STEP_MS}  // sampling period
#define EF_N_SENSORS     4
#define EF_N_INPUTS      ({WINDOW} * 4)

// Order: temperature, humidity, co2, light
{arr("EF_IN_MEAN", norm["input_mean"])}
{arr("EF_IN_STD", norm["input_std"])}
{arr("EF_REL_STD", norm["rel_std"])}
{arr("EF_DELTA_STD", norm["delta_std"])}
"""
    with open(FW_HEADER, "w", encoding="utf-8") as f:
        f.write(text)


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--synthetic", default=os.path.join(HERE, "forecast_sequences.csv"))
    ap.add_argument("--real", default=os.path.join(HERE, "real_sequences.csv"),
                    help="Optional real ESP32 recording (record_real_data.py)")
    ap.add_argument("--real-weight", type=int, default=3,
                    help="Repeat real windows N times so they matter more than synthetic")
    ap.add_argument("--epochs", type=int, default=60)
    ap.add_argument("--seed", type=int, default=42)
    args = ap.parse_args()

    os.environ.setdefault("TF_CPP_MIN_LOG_LEVEL", "2")
    import tensorflow as tf
    from tensorflow import keras

    rng = random.Random(args.seed)
    np.random.seed(args.seed)
    tf.random.set_seed(args.seed)
    os.makedirs(MODEL_DIR, exist_ok=True)

    # ── Load ──
    seqs = load_sequences(args.synthetic, "syn")
    print(f"Synthetic sequences: {len(seqs)}")
    real = []
    if args.real and os.path.exists(args.real):
        real = load_sequences(args.real, "real")
        print(f"Real sequences:      {len(real)}  (weight x{args.real_weight})")
    else:
        print("Real sequences:      none (run record_real_data.py to add some)")

    (Xtr, Ytr), (Xte, Yte) = build_split(seqs, 0.2, rng)
    if real:
        (Xr_tr, Yr_tr), (Xr_te, Yr_te) = build_split(real, 0.2, rng) if len(real) > 1 else \
            (make_windows(real[0]), make_windows(real[0]))
        Xtr = np.concatenate([Xtr] + [Xr_tr] * args.real_weight)
        Ytr = np.concatenate([Ytr] + [Yr_tr] * args.real_weight)
        Xte = np.concatenate([Xte, Xr_te])
        Yte = np.concatenate([Yte, Yr_te])

    # ── Normalize (train statistics only) ──
    in_mean = Xtr[:, -1, :].mean(axis=0)
    in_std = Xtr[:, -1, :].std(axis=0) + 1e-6
    rel_std = (Xtr[:, :-1, :] - Xtr[:, -1:, :]).reshape(-1, 4).std(axis=0) + 1e-6
    d_std = Ytr.std(axis=0) + 1e-6

    def norm_x(X):
        rel = (X[:, :-1, :] - X[:, -1:, :]) / rel_std            # trend vs. now
        cur = (X[:, -1:, :] - in_mean) / in_std                  # current level
        return np.concatenate([rel, cur], axis=1).reshape(len(X), -1).astype(np.float32)

    Xtr_n, Xte_n = norm_x(Xtr), norm_x(Xte)
    Ytr_n, Yte_n = (Ytr / d_std).astype(np.float32), (Yte / d_std).astype(np.float32)
    print(f"Train windows: {len(Xtr_n)}   Test windows: {len(Xte_n)}   Inputs: {Xtr_n.shape[1]}")

    # ── Model ──
    model = keras.Sequential([
        keras.layers.Input(shape=(WINDOW * 4,), name="x"),
        keras.layers.Dense(48, activation="relu"),
        keras.layers.Dense(24, activation="relu"),
        keras.layers.Dense(4, name="delta"),   # Δtemp, Δhum, Δco2, Δlight (normalized)
    ])
    model.compile(optimizer=keras.optimizers.Adam(2e-3), loss="huber", metrics=["mae"])
    model.summary()
    model.fit(
        Xtr_n, Ytr_n, validation_split=0.1, epochs=args.epochs, batch_size=256, verbose=2,
        callbacks=[keras.callbacks.EarlyStopping(patience=12, restore_best_weights=True),
                   keras.callbacks.ReduceLROnPlateau(patience=4, factor=0.5)],
    )

    # ── Evaluate in real units vs. "no change" baseline ──
    pred = model.predict(Xte_n, verbose=0) * d_std
    mae_model = np.abs(pred - Yte).mean(axis=0)
    mae_base = np.abs(Yte).mean(axis=0)   # persistence: future == now
    print("\n=== Test error @ +10 min (lower is better) ===")
    print(f"{'sensor':<12}{'model MAE':>12}{'no-change MAE':>16}{'improvement':>14}")
    for i, s in enumerate(SENSORS):
        imp = 100 * (1 - mae_model[i] / mae_base[i])
        print(f"{s:<12}{mae_model[i]:>9.2f} {UNITS[i]:<4}{mae_base[i]:>11.2f} {UNITS[i]:<4}{imp:>10.0f} %")

    # ── Danger-zone early-warning check (temperature > 27 °C within 10 min) ──
    now_T = Xte[:, -1, 0]
    fut_T = now_T + Yte[:, 0]
    pred_T = now_T + pred[:, 0]
    mask = now_T <= 27.0
    actual = (fut_T > 27.0) & mask
    flagged = (pred_T > 27.0) & mask
    if actual.sum():
        recall = (actual & flagged).sum() / actual.sum()
        precision = (actual & flagged).sum() / max(1, flagged.sum())
        print(f"\nEarly warning (temp will cross 27 °C in 10 min while still below it now):")
        print(f"  caught {recall*100:.0f}% of upcoming spikes, precision {precision*100:.0f}%")

    # ── Export ──
    model.save(os.path.join(MODEL_DIR, "forecaster.keras"))

    conv = tf.lite.TFLiteConverter.from_keras_model(model)
    with open(os.path.join(MODEL_DIR, "forecaster_float32.tflite"), "wb") as f:
        f.write(conv.convert())

    rep = Xtr_n[np.random.choice(len(Xtr_n), min(1000, len(Xtr_n)), replace=False)]

    def rep_gen():
        for r in rep[:300]:
            yield [r.reshape(1, -1)]

    conv = tf.lite.TFLiteConverter.from_keras_model(model)
    conv.optimizations = [tf.lite.Optimize.DEFAULT]
    conv.representative_dataset = rep_gen
    conv.target_spec.supported_ops = [tf.lite.OpsSet.TFLITE_BUILTINS_INT8]
    conv.inference_input_type = tf.int8
    conv.inference_output_type = tf.int8
    int8_model = conv.convert()
    with open(os.path.join(MODEL_DIR, "forecaster_int8.tflite"), "wb") as f:
        f.write(int8_model)

    np.save(os.path.join(MODEL_DIR, "representative.npy"), rep.astype(np.float32))
    np.save(os.path.join(MODEL_DIR, "test_x.npy"), Xte_n[:500])
    np.save(os.path.join(MODEL_DIR, "test_y.npy"), Yte_n[:500])

    # Sanity-check int8 model accuracy
    interp = tf.lite.Interpreter(model_content=int8_model)
    interp.allocate_tensors()
    inp, out = interp.get_input_details()[0], interp.get_output_details()[0]
    s_in, z_in = inp["quantization"]
    s_out, z_out = out["quantization"]
    n_chk = len(Xte_n)
    q_pred = np.zeros((n_chk, 4), dtype=np.float32)
    for i in range(n_chk):
        q = np.clip(np.round(Xte_n[i] / s_in + z_in), -128, 127).astype(np.int8).reshape(1, -1)
        interp.set_tensor(inp["index"], q)
        interp.invoke()
        q_pred[i] = (interp.get_tensor(out["index"]).astype(np.float32) - z_out) * s_out
    q_mae = np.abs(q_pred * d_std - Yte[:n_chk]).mean(axis=0)
    print("\nint8 model MAE: " + ", ".join(f"{s} {q_mae[i]:.2f} {UNITS[i]}" for i, s in enumerate(SENSORS)))

    norm = {
        "sensors": SENSORS, "window": WINDOW, "horizon": HORIZON, "step_ms": STEP_MS,
        "input_mean": in_mean.tolist(), "input_std": in_std.tolist(),
        "rel_std": rel_std.tolist(), "delta_std": d_std.tolist(),
        "feature_layout": "interleaved [T,H,CO2,L] x WINDOW, oldest first; steps 0..W-2 = (x-x_latest)/rel_std, last step = (x-mean)/std",
        "output": "normalized delta; multiply by delta_std and add current value",
    }
    with open(os.path.join(MODEL_DIR, "normalization.json"), "w", encoding="utf-8") as f:
        json.dump(norm, f, indent=2)
    write_c_header(norm)

    size_kb = len(int8_model) / 1024
    print(f"\n[OK] int8 model: {size_kb:.1f} KB -> {os.path.join(MODEL_DIR, 'forecaster_int8.tflite')}")
    print(f"[OK] firmware header -> {FW_HEADER}")
    print("Next: upload forecaster_int8.tflite + representative.npy to Edge Impulse (see EDGE_IMPULSE_TUTORIAL.md)")


if __name__ == "__main__":
    main()
