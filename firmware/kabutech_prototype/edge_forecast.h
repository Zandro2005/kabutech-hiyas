/*
 * ============================================================
 *  KABUTECH HIYAS — Edge AI Forecaster (Edge Impulse)
 * ============================================================
 *  Predicts temperature / humidity / CO2 / light 10 minutes ahead from the
 *  last 10 minutes of readings, so runAutoRegulation() can switch actuators
 *  ON *before* a value reaches the danger zone.
 *
 *  Model : tinyml/train_forecaster.py  ->  Edge Impulse BYOM  ->  Arduino library
 *  Input : 20 samples x 4 sensors (30 s apart), normalized, oldest first,
 *          interleaved [T, H, CO2, L] per sample  (must match the trainer!)
 *  Output: 4 normalized deltas  (a_dtemp, b_dhum, c_dco2, d_dlight)
 *
 *  HOW TO ENABLE
 *    1. Install the Edge Impulse Arduino library .zip (Sketch > Include Library > Add .ZIP)
 *    2. Set ENABLE_EDGE_AI to 1 below
 *    3. If your Edge Impulse project is not named "kabutech_forecast", change EF_EI_HEADER
 *
 *  With ENABLE_EDGE_AI 0 the sketch still compiles; predictions stay invalid
 *  (aiReady == false) and AUTO mode behaves exactly as before.
 * ============================================================
 */
#pragma once

#ifndef ENABLE_EDGE_AI
#define ENABLE_EDGE_AI 0          // 1 = run the Edge Impulse model
#endif

#ifndef CSV_LOG_MODE
#define CSV_LOG_MODE 0            // 1 = print "CSV:" lines for tinyml/record_real_data.py
#endif

#define EF_EI_HEADER <KabuTech_Edge_inferencing.h>

#include "edge_forecast_norm.h"   // AUTO-GENERATED by train_forecaster.py

#if ENABLE_EDGE_AI
#include EF_EI_HEADER
#endif

// ─── Public state (read by runAutoRegulation / pushToFirebase / Serial) ───
bool  aiReady       = false;      // true once a valid forecast exists (>= 2 healthy input channels)
// Per-channel forecast validity (0=temp, 1=hum, 2=co2, 3=light). A forecast for a channel whose
// sensor is faulty is INVALID even when aiReady is true; consumers must check both.
bool  aiChannelValid[4] = { false, false, false, false };
float predTemp10m   = -999.0f;
float predHum10m    = -999.0f;
float predCO2_10m   = -999.0f;
float predLight10m  = -999.0f;
const char* aiAction = "warming_up";   // "warming_up", "none", "preempt_exhaust", ...
unsigned long aiLastInferenceUs = 0;

// ─── Ring buffer ───
static float  efBuf[EF_WINDOW][EF_N_SENSORS];
static int    efHead      = 0;      // next write slot
static int    efCount     = 0;      // samples stored (<= EF_WINDOW)
static bool   efChanBad[EF_N_SENSORS] = { false, false, false, false };  // channel's sensor currently faulty
static float  efLastGood[EF_N_SENSORS] = { -999.0f, -999.0f, -999.0f, -999.0f };
static unsigned long efLastSample = 0;

// ─── Fast-Track Event-Driven Delta Trigger ───
// Bypasses 30-second timer when a sudden spike occurs (e.g. testing or sudden environmental change)
#define FAST_TRIGGER_TEMP_DELTA   1.0f   // 1.0°C significant jump (prevents 0.3°C noise flickering)
#define FAST_TRIGGER_HUM_DELTA    4.0f   // 4.0% RH significant jump/drop
#define FAST_TRIGGER_CO2_DELTA    80.0f  // 80 ppm significant jump
#define FAST_TRIGGER_MIN_INTERVAL 8000   // Min 8 seconds between fast inferences (prevents thrashing/flickering)
static float lastInferredVals[EF_N_SENSORS] = { -999.0f, -999.0f, -999.0f, -999.0f };
static unsigned long lastFastInferenceTime = 0;

#if ENABLE_EDGE_AI
static float efFeatures[EF_N_INPUTS];

static int efGetData(size_t offset, size_t length, float* out_ptr) {
  memcpy(out_ptr, efFeatures + offset, length * sizeof(float));
  return 0;
}

static void efRunInference() {
  // Build features: oldest -> newest, interleaved (MUST match train_forecaster.py)
  //   steps 0..W-2 : (x[i] - x[latest]) / EF_REL_STD   (trend relative to now)
  //   step  W-1    : (x[latest] - EF_IN_MEAN) / EF_IN_STD (current absolute level)
  int start  = efHead;                                   // oldest slot (buffer is full)
  int newest = (efHead - 1 + EF_WINDOW) % EF_WINDOW;
  for (int i = 0; i < EF_WINDOW; i++) {
    int slot = (start + i) % EF_WINDOW;
    for (int s = 0; s < EF_N_SENSORS; s++) {
      efFeatures[i * EF_N_SENSORS + s] = (i < EF_WINDOW - 1)
          ? (efBuf[slot][s] - efBuf[newest][s]) / EF_REL_STD[s]
          : (efBuf[newest][s] - EF_IN_MEAN[s]) / EF_IN_STD[s];
    }
  }

  signal_t signal;
  signal.total_length = EF_N_INPUTS;
  signal.get_data = &efGetData;

  ei_impulse_result_t result = { 0 };
  unsigned long t0 = micros();
  EI_IMPULSE_ERROR err = run_classifier(&signal, &result, false);
  aiLastInferenceUs = micros() - t0;

  if (err != EI_IMPULSE_OK) {
    Serial.printf("   ❌ [Edge AI] run_classifier failed (%d)\n", (int)err);
    aiReady = false;
    return;
  }

  // Outputs are exposed as 4 "labels" a_dtemp, b_dhum, c_dco2, d_dlight (see tutorial)
  float d[EF_N_SENSORS] = { 0, 0, 0, 0 };
  for (size_t i = 0; i < EI_CLASSIFIER_LABEL_COUNT && i < EF_N_SENSORS; i++) {
    d[i] = result.classification[i].value * EF_DELTA_STD[i];
  }

  float rawPredTemp  = efBuf[newest][0] + d[0];
  float rawPredHum   = constrain(efBuf[newest][1] + d[1], 0.0f, 100.0f);
  float rawPredCO2   = max(400.0f, efBuf[newest][2] + d[2]);
  float rawPredLight = max(0.0f, efBuf[newest][3] + d[3]);

  // Per-channel smoothing: each channel smooths independently so a faulty channel (published as
  // -999) never resets the smoothing of the healthy ones. Faulty channels get an INVALID forecast.
  float rawPred[EF_N_SENSORS] = { rawPredTemp, rawPredHum, rawPredCO2, rawPredLight };
  float* pred[EF_N_SENSORS]   = { &predTemp10m, &predHum10m, &predCO2_10m, &predLight10m };
  for (int s = 0; s < EF_N_SENSORS; s++) {
    if (efChanBad[s]) {
      *pred[s] = -999.0f;
      aiChannelValid[s] = false;
    } else {
      *pred[s] = (*pred[s] > -500.0f) ? (0.70f * (*pred[s]) + 0.30f * rawPred[s]) : rawPred[s];
      aiChannelValid[s] = true;
    }
  }
  aiReady = true;

  Serial.printf("🔮 [Edge AI] +10 min forecast: T=%.1f°C  H=%.1f%%  CO2=%.0fppm  L=%.0flx  (%lu µs)\n",
                predTemp10m, predHum10m, predCO2_10m, predLight10m, aiLastInferenceUs);
}
#endif

// Call every loop pass (cheap). Samples every EF_STEP_MS or runs on sudden delta spike.
void edgeForecastTick(unsigned long now, float temp, float hum, int co2, int light,
                      bool shtErr, bool co2Err, bool lightErr) {
  float vals[EF_N_SENSORS] = { temp, hum, (float)co2, (float)light };
  bool  bad[EF_N_SENSORS]  = { shtErr || temp <= -50, shtErr || hum <= 0, co2Err || co2 <= 0, lightErr || light < 0 };

  // ── Per-channel isolation ──
  // A faulty channel is replaced by its last good value (or the training mean if it was never good)
  // ONLY so the fixed-size model input stays well-formed. Its own forecast is published as invalid,
  // and the healthy channels keep getting forecasts. One unplugged sensor must never disable the AI
  // for the others (previously: never-good channel => AI never started; held >50% => AI off for all).
  int goodCount = 0;
  float* predPtrs[EF_N_SENSORS] = { &predTemp10m, &predHum10m, &predCO2_10m, &predLight10m };
  for (int s = 0; s < EF_N_SENSORS; s++) {
    efChanBad[s] = bad[s];
    if (bad[s]) {
      vals[s] = (efLastGood[s] > -900.0f) ? efLastGood[s] : EF_IN_MEAN[s];
      *predPtrs[s] = -999.0f;
      aiChannelValid[s] = false;
    } else {
      efLastGood[s] = vals[s];
      goodCount++;
    }
  }

  // Fewer than 2 healthy inputs: the window would be mostly fabricated -> don't record, don't infer.
  // Reset the window so the first healthy reading after recovery re-seeds it instantly.
  if (goodCount < 2) {
    efCount = 0;
    efHead  = 0;
    aiReady = false;
    for (int s = 0; s < EF_N_SENSORS; s++) aiChannelValid[s] = false;
    aiAction = (millis() < 20000) ? "warming_up" : "sensor_fault";
    return;
  }
  bool anyBad = (goodCount < EF_N_SENSORS);

  // Check if standard 30-second sample period has elapsed (an empty window always samples immediately)
  bool isPeriodicSample = (efCount == 0 || efLastSample == 0 || (now - efLastSample >= EF_STEP_MS));

  // Check if sudden environmental spike occurred (Fast-Track Event Trigger) on any HEALTHY channel
  bool isFastSpike = false;
  if (!isPeriodicSample && efCount == EF_WINDOW && (now - lastFastInferenceTime >= FAST_TRIGGER_MIN_INTERVAL)) {
    if (lastInferredVals[0] > -500.0f) {
      const float spikeThr[3] = { FAST_TRIGGER_TEMP_DELTA, FAST_TRIGGER_HUM_DELTA, FAST_TRIGGER_CO2_DELTA };
      for (int s = 0; s < 3; s++) {
        if (!efChanBad[s] && fabsf(vals[s] - lastInferredVals[s]) >= spikeThr[s]) isFastSpike = true;
      }
    }
  }

  // If neither periodic sample nor fast spike, exit early
  if (!isPeriodicSample && !isFastSpike) return;

  if (isPeriodicSample) {
    efLastSample = now;
  }

#if CSV_LOG_MODE
  if (!anyBad && isPeriodicSample) {
    Serial.printf("CSV:%lu,%.2f,%.2f,%d,%d\n", now, vals[0], vals[1], (int)vals[2], (int)vals[3]);
  }
#endif

  // ── Fast Warm-Up Seeding ──
  // If this is our very first usable sample, seed all 20 slots with it!
  // This lets the AI activate immediately rather than waiting 10 full minutes.
  if (efCount == 0) {
    for (int i = 0; i < EF_WINDOW; i++) {
      for (int s = 0; s < EF_N_SENSORS; s++) efBuf[i][s] = vals[s];
    }
    efCount = EF_WINDOW;
    efHead = 0;
    Serial.println("⚡ [Edge AI] Buffer fast-seeded with first live reading! AI active immediately.");
  } else if (isPeriodicSample) {
    // Normal 30s cadence: advance ring buffer to next time slot
    for (int s = 0; s < EF_N_SENSORS; s++) efBuf[efHead][s] = vals[s];
    efHead = (efHead + 1) % EF_WINDOW;
    if (efCount < EF_WINDOW) efCount++;
  } else if (isFastSpike) {
    // Fast spike event: update newest slot in-place with the live spike value!
    int newest = (efHead - 1 + EF_WINDOW) % EF_WINDOW;
    for (int s = 0; s < EF_N_SENSORS; s++) efBuf[newest][s] = vals[s];
    Serial.printf("⚡ [Edge AI Fast-Track] Sudden climate spike detected (ΔT=%.2f°C, ΔH=%.1f%%, ΔCO2=%.0f ppm) -> Running instant inference!\n",
                  fabsf(vals[0] - lastInferredVals[0]),
                  fabsf(vals[1] - lastInferredVals[1]),
                  fabsf(vals[2] - lastInferredVals[2]));
  }

  if (efCount < EF_WINDOW) {
    aiReady = false;
    for (int s = 0; s < EF_N_SENSORS; s++) aiChannelValid[s] = false;
    aiAction = "warming_up";
    return;
  }

  // Update last inferred values tracking
  for (int s = 0; s < EF_N_SENSORS; s++) {
    lastInferredVals[s] = vals[s];
  }
  lastFastInferenceTime = now;

#if ENABLE_EDGE_AI
  efRunInference();
#else
  aiReady = false;
  for (int s = 0; s < EF_N_SENSORS; s++) aiChannelValid[s] = false;
  aiAction = "disabled";
#endif
}
