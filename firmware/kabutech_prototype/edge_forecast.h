/*
 * ============================================================
 *  KABUTECH HIYAS — Edge AI Forecaster (Edge Impulse)
 * ============================================================
 *  Predicts temperature / humidity / CO2 / light 10 minutes ahead from the
 *  last 10 minutes of readings, so runAutoRegulation() can switch actuators
 *  ON *before* a value reaches the danger zone.
 *
 *  Model : tinyml/train_forecaster.py  ->  Edge Impulse BYOM  ->  Arduino library
 *  Input : 20 samples x 4 sensors (30 s apart), normalized, oldest first,
 *          interleaved [T, H, CO2, L] per sample  (must match the trainer!)
 *  Output: 4 normalized deltas  (a_dtemp, b_dhum, c_dco2, d_dlight)
 *
 *  HOW TO ENABLE
 *    1. Install the Edge Impulse Arduino library .zip (Sketch > Include Library > Add .ZIP)
 *    2. Set ENABLE_EDGE_AI to 1 below
 *    3. If your Edge Impulse project is not named "kabutech_forecast", change EF_EI_HEADER
 *
 *  With ENABLE_EDGE_AI 0 the sketch still compiles; predictions stay invalid
 *  (aiReady == false) and AUTO mode behaves exactly as before.
 * ============================================================
 */
#pragma once

#ifndef ENABLE_EDGE_AI
#define ENABLE_EDGE_AI 0          // 1 = run the Edge Impulse model
#endif

#ifndef CSV_LOG_MODE
#define CSV_LOG_MODE 0            // 1 = print "CSV:" lines for tinyml/record_real_data.py
#endif

#define EF_EI_HEADER <KabuTech_Edge_inferencing.h>

#include "edge_forecast_norm.h"   // AUTO-GENERATED by train_forecaster.py

#if ENABLE_EDGE_AI
#include EF_EI_HEADER
#endif

// ─── Public state (read by runAutoRegulation / pushToFirebase / Serial) ───
bool  aiReady       = false;      // true once a valid forecast exists
float predTemp10m   = -999.0f;
float predHum10m    = -999.0f;
float predCO2_10m   = -999.0f;
float predLight10m  = -999.0f;
const char* aiAction = "warming_up";   // "warming_up", "none", "preempt_exhaust", ...
unsigned long aiLastInferenceUs = 0;

// ─── Ring buffer ───
static float  efBuf[EF_WINDOW][EF_N_SENSORS];
static int    efHead      = 0;      // next write slot
static int    efCount     = 0;      // samples stored (<= EF_WINDOW)
static int    efHeldCount = 0;      // samples in window that reused a stale value
static bool   efHeld[EF_WINDOW];
static float  efLastGood[EF_N_SENSORS] = { -999.0f, -999.0f, -999.0f, -999.0f };
static unsigned long efLastSample = 0;

#if ENABLE_EDGE_AI
static float efFeatures[EF_N_INPUTS];

static int efGetData(size_t offset, size_t length, float* out_ptr) {
  memcpy(out_ptr, efFeatures + offset, length * sizeof(float));
  return 0;
}

static void efRunInference() {
  // Build features: oldest -> newest, interleaved (MUST match train_forecaster.py)
  //   steps 0..W-2 : (x[i] - x[latest]) / EF_REL_STD   (trend relative to now)
  //   step  W-1    : (x[latest] - EF_IN_MEAN) / EF_IN_STD (current absolute level)
  int start  = efHead;                                   // oldest slot (buffer is full)
  int newest = (efHead - 1 + EF_WINDOW) % EF_WINDOW;
  for (int i = 0; i < EF_WINDOW; i++) {
    int slot = (start + i) % EF_WINDOW;
    for (int s = 0; s < EF_N_SENSORS; s++) {
      efFeatures[i * EF_N_SENSORS + s] = (i < EF_WINDOW - 1)
          ? (efBuf[slot][s] - efBuf[newest][s]) / EF_REL_STD[s]
          : (efBuf[newest][s] - EF_IN_MEAN[s]) / EF_IN_STD[s];
    }
  }

  signal_t signal;
  signal.total_length = EF_N_INPUTS;
  signal.get_data = &efGetData;

  ei_impulse_result_t result = { 0 };
  unsigned long t0 = micros();
  EI_IMPULSE_ERROR err = run_classifier(&signal, &result, false);
  aiLastInferenceUs = micros() - t0;

  if (err != EI_IMPULSE_OK) {
    Serial.printf("   ❌ [Edge AI] run_classifier failed (%d)\n", (int)err);
    aiReady = false;
    return;
  }

  // Outputs are exposed as 4 "labels" a_dtemp, b_dhum, c_dco2, d_dlight (see tutorial)
  float d[EF_N_SENSORS] = { 0, 0, 0, 0 };
  for (size_t i = 0; i < EI_CLASSIFIER_LABEL_COUNT && i < EF_N_SENSORS; i++) {
    d[i] = result.classification[i].value * EF_DELTA_STD[i];
  }

  predTemp10m  = efBuf[newest][0] + d[0];
  predHum10m   = constrain(efBuf[newest][1] + d[1], 0.0f, 100.0f);
  predCO2_10m  = max(400.0f, efBuf[newest][2] + d[2]);
  predLight10m = max(0.0f, efBuf[newest][3] + d[3]);
  aiReady = true;

  Serial.printf("🔮 [Edge AI] +10 min forecast: T=%.1f°C  H=%.1f%%  CO2=%.0fppm  L=%.0flx  (%lu µs)\n",
                predTemp10m, predHum10m, predCO2_10m, predLight10m, aiLastInferenceUs);
}
#endif

// Call every loop pass (cheap). Samples every EF_STEP_MS and runs inference.
void edgeForecastTick(unsigned long now, float temp, float hum, int co2, int light,
                      bool shtErr, bool co2Err, bool lightErr) {
  if (efLastSample != 0 && now - efLastSample < EF_STEP_MS) return;
  efLastSample = now;

  float vals[EF_N_SENSORS] = { temp, hum, (float)co2, (float)light };
  bool  bad[EF_N_SENSORS]  = { shtErr || temp <= -50, shtErr || hum <= 0, co2Err || co2 <= 0, lightErr || light < 0 };

  bool held = false;
  for (int s = 0; s < EF_N_SENSORS; s++) {
    if (bad[s]) {
      if (efLastGood[s] <= -999.0f) return;   // never had a good value yet -> skip sample
      vals[s] = efLastGood[s];
      held = true;
    } else {
      efLastGood[s] = vals[s];
    }
  }

#if CSV_LOG_MODE
  if (!held) {
    Serial.printf("CSV:%lu,%.2f,%.2f,%d,%d\n", now, vals[0], vals[1], (int)vals[2], (int)vals[3]);
  }
#endif

  // ── Fast Warm-Up Seeding ──
  // If this is our very first valid sample, seed all 20 slots with it!
  // This lets the AI activate in 30 seconds rather than waiting 10 full minutes.
  if (efCount == 0 && !held) {
    for (int i = 0; i < EF_WINDOW; i++) {
      for (int s = 0; s < EF_N_SENSORS; s++) efBuf[i][s] = vals[s];
      efHeld[i] = false;
    }
    efCount = EF_WINDOW;
    efHeldCount = 0;
    efHead = 0;
    Serial.println("⚡ [Edge AI] Buffer fast-seeded with first live reading! AI active immediately.");
  } else {
    if (efCount == EF_WINDOW && efHeld[efHead]) efHeldCount--;   // overwriting a held slot
    for (int s = 0; s < EF_N_SENSORS; s++) efBuf[efHead][s] = vals[s];
    efHeld[efHead] = held;
    if (held) efHeldCount++;
    efHead = (efHead + 1) % EF_WINDOW;
    if (efCount < EF_WINDOW) efCount++;
  }

  if (efCount < EF_WINDOW) {
    aiReady = false;
    aiAction = "warming_up";
    return;
  }
  if (efHeldCount > EF_WINDOW / 2) {          // too many stale readings -> don't trust it
    aiReady = false;
    aiAction = "sensor_fault";
    return;
  }

#if ENABLE_EDGE_AI
  efRunInference();
#else
  aiReady = false;
  aiAction = "disabled";
#endif
}
